def count_han(text: str) -> int:
    return len(HAN_RE.findall(text or ""))


def pick_priority(used: set[str], preferred: str) -> str:
    if preferred not in used:
        return preferred
    for p in ("P4", "P3", "P2", "P1", "P0"):
        if p not in used:
            return p
    return "P4"  # 附加 F 可与实物 P4 并存


def find_witness_file(witness_dir: Path, eid: str, name: str) -> Path | None:
    matches = list(witness_dir.glob(f"{eid}_*_见证.json"))
    if matches:
        return matches[0]
    for fp in witness_dir.glob(f"{eid}_*_见证.json"):
        return fp
    return None


def append_one(witness_dir: Path, eid: str, payload: dict) -> dict:
    fp = witness_dir / payload.get("file", "")
    if not fp.is_file():
        cands = list(witness_dir.glob(f"{eid}_*_见证.json"))
        if not cands:
            return {"eid": eid, "status": "missing_file"}
        fp = cands[0]

    doc = json.loads(fp.read_text(encoding="utf-8"))
    entries = doc.get("entries") or []
    if any(e.get("附加文学见证") for e in entries):
        return {"eid": eid, "file": fp.name, "status": "already_has_extra_f"}

    spec = LITERARY_ENTRIES[eid]
    hc = count_han(spec["文物介绍"])
    if hc < 100 or hc > 200:
        return {"eid": eid, "file": fp.name, "status": f"intro_han_{hc}_out_of_range"}

    rc = count_han(spec["优先级判定理由"])
    if rc < 20 or rc > 80:
        return {"eid": eid, "file": fp.name, "status": f"reason_han_{rc}_out_of_range"}

    used_pri = {str(e.get("文物优先级") or "").upper() for e in entries}
    pri = pick_priority(used_pri, spec["文物优先级"])

    name = str(doc.get("史略名称") or "")
    new_idx = len(entries) + 1
    new_entry = {
        "文物ID": f"{eid}_W{new_idx:02d}",
        "文物标题": spec["文物标题"],
        "史略ID": eid,
        "史略名称": name,
        "现藏地点": spec["现藏地点"],
        "文物介绍": spec["文物介绍"],
        "文物图片": "",
        "文物优先级": pri,
        "优先级判定理由": spec["优先级判定理由"],
        "附加文学见证": True,
    }
    entries.append(new_entry)
    doc["entries"] = entries
    doc["entry_count"] = len(entries)
    doc["status"] = "done"
    doc["processed_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    fp.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return {"eid": eid, "file": fp.name, "status": "ok", "wid": new_entry["文物ID"], "intro_han": hc}


def main() -> None:
    paths = histograph_paths()
    witness_dir = paths["witness"]
    refined = json.loads(REFINED.read_text(encoding="utf-8"))
    results = []
    for item in refined["accepted"]:
        eid = item["史略ID"]
        if eid not in LITERARY_ENTRIES:
            results.append({"eid": eid, "status": "no_payload"})
            continue
        payload = {**item, **LITERARY_ENTRIES[eid]}
        results.append(append_one(witness_dir, eid, payload))

    ok = [r for r in results if r.get("status") == "ok"]
    fail = [r for r in results if r.get("status") != "ok"]
    print(f"写入成功: {len(ok)} / {len(results)}")
    for r in fail:
        print(f"  失败 {r}")
    for r in ok:
        print(f"  ✓ {r['eid']} {r['wid']} ({r['intro_han']}字)")

    # verify
    from verify_cw import verify_file  # noqa: WPS433

    critical = 0
    for r in ok:
        fp = witness_dir / r["file"]
        issues = verify_file(fp, mode="witness", strict=True)
        crit = [i for i in issues if i["level"] == "CRITICAL"]
        if crit:
            critical += 1
            print(f"  verify CRITICAL {r['file']}: {crit[0]['msg']}")
    print(f"verify CRITICAL: {critical}")


if __name__ == "__main__":
    main()
