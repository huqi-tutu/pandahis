rows=[]
for fp in sorted(SPLIT.glob("01史记_*.txt")):
    text=fp.read_text(encoding="utf-8")
    m=re.match(r"01史记_(\d+)_", fp.name)
    vol=m.group(1) if m else "?"
    para_map={}
    ip=IDX/("01史记_%s.json"%vol)
    if ip.exists():
        d=json.loads(ip.read_text(encoding="utf-8"))
        for i,p in enumerate(d.get("paragraphs") or [],1):
            para_map[i]=p.get("text") or ""
    for mi in re.finditer(r"<[^>\n]+>", text):
        tag=mi.group(0); start,end=mi.span()
        line_no=text.count("\n",0,start)+1
        ctx=text[max(0,start-22):end+22].replace("\n"," ")
        pid=""; needle=text[max(0,start-12):end+12].replace("\n","")
        for i,pt in para_map.items():
            if tag in pt and needle[:18] in pt.replace("\n",""):
                pid=i; break
        if pid=="":
            for i,pt in para_map.items():
                if tag in pt: pid=i; break
        meta=MAP.get((vol,tag), {"propose":S(0xFF08,0x672A,0x5EFA,0x6620,0x5C04,0xFF09),"replace_span":tag,"confidence":"C","basis":S(0x5C1A,0x672A,0x5EFA,0x7ACB,0x5BF9,0x52D8,0x6761,0x76EE)})
        rows.append({"vol":vol,"para":pid,"line":line_no,"kind":"分页断字" if tag.endswith(S(0x9875)+">") else "合字拆形","tag":tag,"replace_span":meta["replace_span"],"propose":meta["propose"],"confidence":meta["confidence"],"context":ctx,"basis":meta["basis"],"file":fp.name})

