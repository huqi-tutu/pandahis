def lookup_death_year(entry: dict) -> Optional[int]:
    eid = (entry.get("史略ID") or "").strip()
    if eid in DEATH_BY_EID:
        return DEATH_BY_EID[eid]
    name = (entry.get("史略名称") or "").strip()
    if name in DEATH_BY_NAME:
        return DEATH_BY_NAME[name]
    return None
