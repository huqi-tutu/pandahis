# 名称备用（无 eid 时）
LIFESPANS_BY_NAME: Dict[str, Tuple[int, int, str]] = {}


def lookup_scholarly_lifespan(entry: dict) -> Optional[Tuple[int, int, str]]:
    eid = (entry.get("史略ID") or "").strip()
    if eid in LIFESPANS_BY_EID:
        s, e, note = LIFESPANS_BY_EID[eid]
        return int(s), int(e), note
    name = (entry.get("史略名称") or "").strip()
    if name in LIFESPANS_BY_NAME:
        s, e, note = LIFESPANS_BY_NAME[name]
        return int(s), int(e), note
    return None


def is_death_only_candidate(entry: dict) -> bool:
    eid = (entry.get("史略ID") or "").strip()
    if eid in DEATH_ONLY_EIDS:
        return True
    if lookup_scholarly_lifespan(entry) is not None:
        return False
    return True
